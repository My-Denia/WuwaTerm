export type Messages = typeof zh;

/** Unknown languages and missing keys fall back to Chinese. */
export function msg(lang: UiLanguage): Messages {
  return lang === 'en' ? en : zh;
}

export function fill(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/gu, (_, key: string) => (key in params ? String(params[key]) : `{${key}}`));
}

type SummaryParts = {
  verified: number;
  conflicts: number;
  needs: number;
  notEvaluated: number;
  truncated: boolean;
  zeroCoverage: boolean;
  headline: 'fail' | 'needs_check' | 'partial_verified';
};

/** The one-sentence review summary, identical in wording to summarizeReview() for zh. */
export function summarySentence(parts: SummaryParts, lang: UiLanguage): string {
  const m = msg(lang).summary;
  const segments = [
    fill(m.verified, { n: parts.verified }),
    fill(m.conflicts, { n: parts.conflicts }),
    fill(m.needs, { n: parts.needs }),
  ];
  if (parts.notEvaluated > 0) segments.push(fill(m.notEvaluated, { n: parts.notEvaluated }));
  if (parts.truncated) segments.push(m.truncated);
  if (parts.zeroCoverage) segments.push(m.zeroCoverage);
  segments.push(m.noSentenceMeaning);
  return m.prefix + segments.join(lang === 'zh' ? '；' : '; ') + m.suffix;
}

export function summaryHeadline(parts: SummaryParts, lang: UiLanguage): string {
  const m = msg(lang).summary;
  return parts.headline === 'fail' ? m.headlineFail : parts.headline === 'needs_check' ? m.headlineNeedsCheck : m.headlinePartial;
}
